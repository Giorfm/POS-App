/**
 * Generate 30 days of realistic sales, orders, shifts, and stock movements
 */
export function generateSeedHistoricalData(): {
  orders: Order[];
  shifts: Shift[];
  inventoryItems: InventoryItem[];
  stockMovements: StockMovement[];
} {
  const orders: Order[] = [];
  const shifts: Shift[] = [];
  const stockMovements: StockMovement[] = [];
  const inventoryItems: InventoryItem[] = [];

  // Initialize base inventory per outlet
  for (const outlet of SEED_OUTLETS) {
    for (const prod of SEED_PRODUCTS) {
      const initialStock = prod.business_type === 'fnb' ? 60 : 100;
      inventoryItems.push({
        id: `inv_${outlet.id}_${prod.id}`,
        business_id: SEED_BUSINESS.id,
        outlet_id: outlet.id,
        product_id: prod.id,
        variant_id: null,
        stock_quantity: initialStock,
        min_stock: prod.min_stock_alert,
        rack_location: 'A-01',
        created_at: new Date('2026-01-01T00:00:00Z').toISOString(),
        updated_at: new Date('2026-01-01T00:00:00Z').toISOString(),
      });
    }
  }

  // Generate 30 days back from today
  const now = new Date('2026-10-15T08:00:00Z');
  let orderCounter = 1001;

  for (let dayOffset = 29; dayOffset >= 0; dayOffset--) {
    const dayDate = new Date(now.getTime() - dayOffset * 24 * 60 * 60 * 1000);
    const dayStr = dayDate.toISOString().split('T')[0];

    // Day Shift (08:00 - 16:00)
    const shiftId = `shift_${dayStr}_1`;
    let shiftCashTotal = 0;
    let shiftNonCashTotal = 0;

    // Number of transactions for the day (between 12 and 22 orders per day)
    const ordersTodayCount = 14 + ((dayOffset * 7) % 9);

    for (let oIdx = 0; oIdx < ordersTodayCount; oIdx++) {
      const orderHour = 8 + Math.floor((oIdx / ordersTodayCount) * 12);
      const orderMinute = (oIdx * 19) % 60;
      const orderDate = new Date(`${dayStr}T${String(orderHour).padStart(2, '0')}:${String(orderMinute).padStart(2, '0')}:00Z`);

      // Pick 1 to 4 items
      const numItems = 1 + ((oIdx * 3) % 4);
      const itemsList: Order['items'] = [];
      let subtotal = 0;

      for (let i = 0; i < numItems; i++) {
        const prod = SEED_PRODUCTS[(oIdx * 3 + i * 7) % SEED_PRODUCTS.length];
        const qty = 1 + ((oIdx + i) % 2);
        const itemSubtotal = prod.sell_price * qty;
        subtotal += itemSubtotal;

        itemsList.push({
          id: `item_${orderCounter}_${i}`,
          order_id: `ord_${orderCounter}`,
          business_id: SEED_BUSINESS.id,
          product_id: prod.id,
          variant_id: null,
          product_name: prod.name,
          variant_name: null,
          sku: prod.sku,
          buy_price: prod.buy_price,
          unit_price: prod.sell_price,
          quantity: qty,
          subtotal: itemSubtotal,
          discount_amount: 0,
          final_price: itemSubtotal,
          modifiers: [],
          created_at: orderDate.toISOString(),
        });

        // Deduct inventory item stock
        const inv = inventoryItems.find((invItem) => invItem.product_id === prod.id && invItem.outlet_id === 'outlet_sudirman');
        if (inv) {
          const prev = inv.stock_quantity;
          inv.stock_quantity = Math.max(0, inv.stock_quantity - qty);
          stockMovements.push({
            id: `sm_${orderCounter}_${i}`,
            business_id: SEED_BUSINESS.id,
            outlet_id: 'outlet_sudirman',
            product_id: prod.id,
            variant_id: null,
            type: 'sale',
            quantity: -qty,
            previous_stock: prev,
            current_stock: inv.stock_quantity,
            reference_id: `ORD-${orderCounter}`,
            notes: 'Penjualan kasir',
            created_by: 'user_cashier_1',
            created_at: orderDate.toISOString(),
          });
        }
      }

      // Tax (PPN 11%)
      const taxAmount = Math.round((subtotal * 11) / 100);
      const rawGrandTotal = subtotal + taxAmount;
      // Round to 100
      const remainder = rawGrandTotal % 100;
      const roundingAmount = remainder === 0 ? 0 : remainder >= 50 ? 100 - remainder : -remainder;
      const grandTotal = rawGrandTotal + roundingAmount;

      const isCash = oIdx % 2 === 0;
      const paymentMethod = isCash ? 'cash' : 'qris';
      const paidAmount = isCash ? Math.ceil(grandTotal / 10000) * 10000 : grandTotal;
      const changeAmount = isCash ? paidAmount - grandTotal : 0;

      if (isCash) {
        shiftCashTotal += grandTotal;
      } else {
        shiftNonCashTotal += grandTotal;
      }

      const assignedCustomer = oIdx % 3 === 0 ? SEED_CUSTOMERS[oIdx % SEED_CUSTOMERS.length] : null;

      orders.push({
        id: `ord_${orderCounter}`,
        business_id: SEED_BUSINESS.id,
        outlet_id: 'outlet_sudirman',
        shift_id: shiftId,
        user_id: oIdx % 2 === 0 ? 'user_cashier_1' : 'user_cashier_2',
        customer_id: assignedCustomer ? assignedCustomer.id : null,
        dining_table_id: null,
        order_number: `ORD-${orderCounter}`,
        order_type: 'retail',
        status: 'completed',
        payment_status: 'paid',
        subtotal,
        discount_amount: 0,
        tax_rate: 11,
        tax_amount: taxAmount,
        service_charge_rate: 0,
        service_charge_amount: 0,
        rounding_amount: roundingAmount,
        grand_total: grandTotal,
        paid_amount: paidAmount,
        change_amount: changeAmount,
        payment_method: paymentMethod,
        items: itemsList,
        created_at: orderDate.toISOString(),
        updated_at: orderDate.toISOString(),
      });

      orderCounter++;
    }

    // Register closed shift for historical days, open shift for today
    const isToday = dayOffset === 0;
    shifts.push({
      id: shiftId,
      business_id: SEED_BUSINESS.id,
      outlet_id: 'outlet_sudirman',
      user_id: 'user_cashier_1',
      start_time: new Date(`${dayStr}T08:00:00Z`).toISOString(),
      end_time: isToday ? null : new Date(`${dayStr}T21:00:00Z`).toISOString(),
      opening_cash: 200000,
      expected_cash: 200000 + shiftCashTotal,
      actual_cash: isToday ? null : 200000 + shiftCashTotal,
      difference_cash: isToday ? null : 0,
      total_sales_cash: shiftCashTotal,
      total_sales_non_cash: shiftNonCashTotal,
      total_refunds: 0,
      total_cash_in: 0,
      total_cash_out: 0,
      status: isToday ? 'open' : 'closed',
      notes: isToday ? 'Shift aktif hari ini' : 'Shift ditutup seimbang',
      created_at: new Date(`${dayStr}T08:00:00Z`).toISOString(),
    });
  }

  return { orders, shifts, inventoryItems, stockMovements };
}
